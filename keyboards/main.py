from vkbottle import Keyboard, Text


def create_main_keyboard(is_teacher: bool, is_admin: bool):
    """Главное меню.

    Раскладка одинаковая для всех ролей:

        [📅 Сегодня] [🔔 Когда звонок]
        [📅 ПН] [📅 ВТ] [📅 СР]
        [📅 ЧТ] [📅 ПТ] [📅 СБ]
        ...служебные кнопки по роли...
        [⚙️ Настройки]              <- всегда последняя, во всю ширину

    Расписание (дни) идёт сверху, служебные кнопки — отдельным блоком внизу,
    «⚙️ Настройки» замыкает клавиатуру у всех, чтобы её положение не зависело
    от роли.
    """

    kb = Keyboard(one_time=False)

    # быстрые действия
    kb.add(Text("📅 Сегодня"))
    kb.add(Text("🔔 Когда звонок"))
    kb.row()

    # дни недели
    kb.add(Text("📅 ПН"))
    kb.add(Text("📅 ВТ"))
    kb.add(Text("📅 СР"))
    kb.row()

    kb.add(Text("📅 ЧТ"))
    kb.add(Text("📅 ПТ"))
    kb.add(Text("📅 СБ"))
    kb.row()

    # служебный блок. У админов обратной связи нет — они её получают.
    if not is_admin:
        kb.add(Text("💬 Обратная связь")).row()

    # панель преподавателя есть и у админов (роль admin включает права teacher)
    if is_teacher:
        kb.add(Text("👨‍🏫 Панель преподавателя")).row()

    if is_admin:
        kb.add(Text("👑 Админ панель")).row()

    # всегда последняя строка, у всех ролей
    kb.add(Text("⚙️ Настройки")).row()

    return kb